/**
 * Build steps of a new-layout node app (split env layout, see db-layout.ts).
 *
 * Bootstrap writes one root-owned script per app,
 * `/usr/local/lib/samohost/apps/<app>/step`. The deploy user runs it through
 * exact sudo rules, one per step name (`step install`, `step build`, ...).
 * The script takes no other input: the commands, users and paths are fixed
 * when bootstrap writes it.
 *
 * Directory model (all under the root-owned /opt/<app>):
 * - app/          the checkout, owned by the deploy user (git fetch and reset).
 * - build/        owned by <app>-build. Install copies the checkout (without
 *                 .git) here, then npm and the build command write here.
 * - build-cache/  owned by <app>-build; the npm cache of install and build
 *                 (npm_config_cache). HOME of every step is its private /tmp.
 * - releases/<n>/ root-owned copies of build/ (group <app>-run, no world bits),
 *                 made by `step release` after migrate.
 * - current, previous: root-owned links to releases/<n>. The service unit
 *                 uses WorkingDirectory=/opt/<app>/current.
 *
 * install, build, migrate and seed run as <app>-build in a transient systemd
 * service with the same hardening as the app unit, plus memory, task and time
 * limits. The service's cgroup ends with the step, so no process of the build
 * user outlives it. migrate and seed get migrate.env through EnvironmentFile=
 * (read by systemd as root) and cannot write anywhere but their private /tmp.
 */

export const BUILD_STEP_NAMES = ["install", "build", "backup", "migrate", "seed", "release", "rollback", "cleanup"] as const;

export interface BuildStepParams {
  appName: string;
  buildUser: string;
  runUser: string;
  appBase: string;
  checkoutDir: string;
  envFile: string;
  migrateEnvFile: string;
  releaseEnvFile: string;
  database: string;
  tokenFile: string;
  gitSafeConf: string;
  buildCmd: string;
  migrateCmd?: string;
  seedCmd?: string;
}

function sq(s: string): string {
  return `'${s.replace(/'/g, `'\\''`)}'`;
}

/** Path of the root-owned step script of an app. */
export function buildStepScriptPath(appName: string): string {
  return `/usr/local/lib/samohost/apps/${appName}/step`;
}

/** The folders of the build model, under the app base directory. */
export function buildModelPaths(appBase: string) {
  return {
    buildDir: `${appBase}/build`,
    cacheDir: `${appBase}/build-cache`,
    releasesDir: `${appBase}/releases`,
    currentLink: `${appBase}/current`,
    previousLink: `${appBase}/previous`,
  };
}

/** Text of the step script (bash). */
export function buildStepScript(p: BuildStepParams): string {
  const m = buildModelPaths(p.appBase);
  const hidden = [p.envFile, p.migrateEnvFile, p.tokenFile, p.gitSafeConf, `${p.checkoutDir}/.git`, m.releasesDir]
    .map((x) => `-${x}`)
    .join(" ");
  // The copy unit reads build/ and writes only the new release folder; the
  // releases folder itself is not hidden there (the folder is inside it).
  const hiddenCopy = [p.envFile, p.migrateEnvFile, p.tokenFile, p.gitSafeConf, `${p.checkoutDir}/.git`]
    .map((x) => `-${x}`)
    .join(" ");
  const copyCmd = [
    "set -euo pipefail",
    'kb="$(du -sk -- "$SRC" | cut -f1)"',
    'if [ "$kb" -gt "$MAX_BUILD_KB" ]; then echo "ERROR: build/ has $kb KiB, more than the limit of $MAX_BUILD_KB KiB; no release was made" >&2; exit 1; fi',
    "avail=\"$(df -Pk -- \"$DEST\" | awk 'NR == 2 { print $4 }')\"",
    'if [ $((avail - kb)) -lt "$MIN_FREE_KB" ]; then echo "ERROR: the copy would leave $((avail - kb)) KiB free on the file system of the releases, less than $MIN_FREE_KB KiB; no release was made" >&2; exit 1; fi',
    'cp -R -P --preserve=timestamps -- "$SRC/." "$DEST/"',
  ].join("; ");
  const installCmd = [
    "set -euo pipefail",
    "chmod -R u+rwX . 2>/dev/null || true",
    'find . -mindepth 1 -maxdepth 1 -exec rm -rf -- {} + || { echo "ERROR: $PWD has entries the build user cannot remove; as root, empty it and deploy again" >&2; exit 1; }',
    'tar -C "$SAMOHOST_CHECKOUT" --exclude=./.git -cf - . | tar --no-overwrite-dir -xf -',
    // --no-overwrite-dir keeps the mode of the existing build/; chmod 700
    // stays in case a tar without that option gives it the mode of the
    // archive's ./ entry (the checkout's).
    "chmod 700 .",
    "if [ -f package-lock.json ] || [ -f npm-shrinkwrap.json ]; then npm ci --include=dev; else npm install --include=dev; fi",
  ].join("; ");
  return [
    "#!/bin/bash",
    `# samohost build steps for app '${p.appName}'. Generated by samohost host-bootstrap;`,
    "# root-owned. The deploy user runs it through exact sudo rules, one per step.",
    "# It takes no other input from the deploy user or the repository.",
    "set -euo pipefail",
    "umask 077",
    "export PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin",
    `APP=${sq(p.appName)}`,
    `BUILD_USER=${sq(p.buildUser)}`,
    `RUN_USER=${sq(p.runUser)}`,
    `CHECKOUT=${sq(p.checkoutDir)}`,
    `BUILD_DIR=${sq(m.buildDir)}`,
    `CACHE_DIR=${sq(m.cacheDir)}`,
    `RELEASES=${sq(m.releasesDir)}`,
    `CURRENT=${sq(m.currentLink)}`,
    `PREVIOUS=${sq(m.previousLink)}`,
    `MIGRATE_ENV=${sq(p.migrateEnvFile)}`,
    `RELEASE_ENV=${sq(p.releaseEnvFile)}`,
    `DATABASE=${sq(p.database)}`,
    `BACKUP_DIR=${sq(`/var/backups/samohost/${p.appName}`)}`,
    `HIDDEN=${sq(hidden)}`,
    `HIDDEN_COPY=${sq(hiddenCopy)}`,
    `COPY_CMD=${sq(copyCmd)}`,
    `INSTALL_CMD=${sq(installCmd)}`,
    `BUILD_CMD=${sq(p.buildCmd)}`,
    `MIGRATE_CMD=${sq(p.migrateCmd ?? "")}`,
    `SEED_CMD=${sq(p.seedCmd ?? "")}`,
    `LOCK=/run/samohost/${p.appName}.lock`,
    "# Disk limits of a release (KiB): the size of build/, and the free space the",
    "# copy must leave on the file system of the releases.",
    "MAX_BUILD_KB=2097152",
    "MIN_FREE_KB=2097152",
    "",
    `if [[ $# -ne 1 ]]; then echo "usage: $0 ${BUILD_STEP_NAMES.join("|")}" >&2; exit 2; fi`,
    'case "$1" in install|build|backup|migrate|seed|release|rollback|cleanup) ;; *)',
    `  echo "usage: $0 ${BUILD_STEP_NAMES.join("|")}" >&2; exit 2 ;;`,
    "esac",
    "",
    "# One lock per app for the whole run of every step: no two steps of this app",
    "# run at the same time (for example a release copy and a second deploy's",
    "# install or build). /run/samohost is root-owned; the lock file is root's.",
    "install -d -m 755 /run/samohost",
    'exec 9>>"$LOCK"',
    "if ! flock -n 9; then",
    '  echo "ERROR: another step of app $APP is running; try again when it has finished" >&2',
    "  exit 1",
    "fi",
    "",
    "# A step unit can outlive its step script when the deploy's connection drops",
    "# (systemd-run --wait is killed, the unit keeps running). Refuse until it ended.",
    "samohost_units_idle() {",
    "  local u state",
    "  for u in install build migrate seed copy; do",
    '    state="$(/usr/bin/systemctl is-active "samohost-$APP-$u" 2>/dev/null || true)"',
    '    case "$state" in',
    '      inactive|failed|unknown|"") ;;',
    '      *) echo "ERROR: samohost-$APP-$u is $state; refusing to run $1 until it has ended" >&2; return 1 ;;',
    "    esac",
    "  done",
    "}",
    'if [[ "$1" != cleanup ]]; then samohost_units_idle "$1" || exit 1; fi',
    "",
    "# Hardening of every step unit (the app unit's, without AF_UNIX: a step cannot",
    "# create a unix socket, so it cannot pass a descriptor to another process",
    "# through an abstract socket; socketpair() is not affected).",
    "HARDENING=(",
    "  -p NoNewPrivileges=yes -p ProtectSystem=strict -p ProtectHome=yes -p PrivateTmp=yes",
    "  -p PrivateDevices=yes -p ProtectKernelTunables=yes -p ProtectKernelModules=yes",
    "  -p ProtectControlGroups=yes -p ProtectProc=invisible -p RestrictSUIDSGID=yes",
    '  -p "RestrictAddressFamilies=AF_INET AF_INET6 AF_NETLINK" -p CapabilityBoundingSet=',
    "  -p LockPersonality=yes -p RestrictNamespaces=yes -p SystemCallFilter=@system-service -p SystemCallErrorNumber=EPERM",
    "  -p SystemCallArchitectures=native -p ProtectClock=yes -p ProtectHostname=yes -p ProtectKernelLogs=yes",
    "  -p RestrictRealtime=yes -p TemporaryFileSystem=/dev/shm -p RemoveIPC=yes",
    ")",
    "",
    "# Run one command as the build user in a transient systemd service. The",
    "# service's cgroup ends with the command (KillMode=control-group), so no",
    "# process of the build user outlives the step.",
    "# Arguments: unit name, time limit (s), writable paths, env file, npm cache",
    "# folder, command. HOME is the unit's private /tmp, so no configuration file",
    "# (~/.npmrc and others) outlives the step; only the npm cache folder persists.",
    "samohost_build_unit() {",
    '  local props=(',
    '    "${HARDENING[@]}"',
    '    -p MemoryMax=75% -p TasksMax=1024 -p "RuntimeMaxSec=$2"',
    '    -p KillMode=control-group -p "InaccessiblePaths=$HIDDEN" -p "EnvironmentFile=-$RELEASE_ENV"',
    "  )",
    "  # No step reaches the cloud metadata address. migrate and seed need PostgreSQL",
    "  # on 127.0.0.1; install and build reach no loopback address except the",
    "  # systemd-resolved stub 127.0.0.53 (name resolution for npm).",
    '  case "$1" in',
    '    migrate|seed) props+=(-p "IPAddressDeny=169.254.169.254") ;;',
    '    *) props+=(-p "IPAddressDeny=169.254.169.254 127.0.0.0/8 ::1" -p IPAddressAllow=127.0.0.53) ;;',
    "  esac",
    '  if [[ -n "$3" ]]; then props+=(-p "ReadWritePaths=$3"); fi',
    '  if [[ -n "$4" ]]; then props+=(-p "EnvironmentFile=$4"); fi',
    '  local envs=(-E HOME=/tmp -E NODE_ENV=production -E PATH=/usr/local/bin:/usr/bin:/bin -E SAMOHOST_CHECKOUT="$CHECKOUT")',
    '  if [[ -n "$5" ]]; then envs+=(-E "npm_config_cache=$5"); fi',
    '  systemd-run --quiet --wait --pipe --collect --service-type=exec \\',
    '    --unit="samohost-$APP-$1" --uid="$BUILD_USER" --gid="$BUILD_USER" \\',
    '    --working-directory="$BUILD_DIR" \\',
    '    "${envs[@]}" "${props[@]}" /bin/bash -c "$6"',
    "}",
    "",
    "# Copy build/ into a new release folder as the build user: the copy can read",
    "# only what the build user can read (not the env files, the token or the",
    "# releases), has no network, and can write only the destination folder.",
    "# It also checks the disk limits (MAX_BUILD_KB, MIN_FREE_KB).",
    "samohost_copy_unit() { # <destination folder>",
    '  systemd-run --quiet --wait --pipe --collect --service-type=exec \\',
    '    --unit="samohost-$APP-copy" --uid="$BUILD_USER" --gid="$BUILD_USER" \\',
    '    --working-directory=/ \\',
    '    -E HOME=/tmp -E PATH=/usr/local/bin:/usr/bin:/bin -E SRC="$BUILD_DIR" -E DEST="$1" \\',
    '    -E MAX_BUILD_KB="$MAX_BUILD_KB" -E MIN_FREE_KB="$MIN_FREE_KB" \\',
    '    "${HARDENING[@]}" -p KillMode=control-group -p MemoryMax=75% -p TasksMax=64 -p RuntimeMaxSec=1800 \\',
    '    -p PrivateNetwork=yes -p IPAddressDeny=any -p "InaccessiblePaths=$HIDDEN_COPY" -p "ReadWritePaths=$1" \\',
    '    /bin/bash -c "$COPY_CMD"',
    "}",
    "",
    "# Remove every entry of releases/ except the targets of current and previous.",
    "samohost_prune() {",
    '  local keep_current="" keep_previous="" d b',
    '  if [[ -L "$CURRENT" ]]; then keep_current="$(basename -- "$(readlink -- "$CURRENT")")"; fi',
    '  if [[ -L "$PREVIOUS" ]]; then keep_previous="$(basename -- "$(readlink -- "$PREVIOUS")")"; fi',
    '  for d in "$RELEASES"/*; do',
    '    [[ -e "$d" || -L "$d" ]] || continue',
    '    b="$(basename -- "$d")"',
    '    if [[ "$b" != "$keep_current" && "$b" != "$keep_previous" ]]; then rm -rf -- "$d" || echo "WARNING: could not remove $d" >&2; fi',
    "  done",
    "}",
    "",
    "samohost_switch_link() { # <link> <target>: replace the link in one rename",
    '  ln -sfn -- "$2" "$1.next"',
    '  mv -fT -- "$1.next" "$1"',
    "}",
    "",
    'case "$1" in',
    "  install)",
    "    # The install unit empties build/ in place, as the build user (INSTALL_CMD).",
    '    pkill -KILL -u "$BUILD_USER" 2>/dev/null || true',
    '    samohost_build_unit install 1800 "$BUILD_DIR $CACHE_DIR" "" "$CACHE_DIR" "$INSTALL_CMD"',
    "    ;;",
    "  build)",
    '    samohost_build_unit build 1800 "$BUILD_DIR $CACHE_DIR" "" "$CACHE_DIR" "$BUILD_CMD"',
    "    ;;",
    "  backup)",
    "    # Root owns the directory and opens the output file. pg_dump itself runs",
    "    # as the postgres OS user over peer authentication and cannot list backups.",
    '    install -d -m 700 -o root -g root "$BACKUP_DIR"',
    '    find "$BACKUP_DIR" -maxdepth 1 -type f -name ".backup.*.tmp" -delete',
    '    sha="$(sed -n "s/^SAMO_RELEASE_SHA=//p" "$RELEASE_ENV" | tail -n 1)"',
    '    if [[ ! "$sha" =~ ^[0-9a-f]{7,64}$ ]]; then echo "ERROR: release.env has no valid SAMO_RELEASE_SHA; database backup did not run" >&2; exit 1; fi',
    '    stamp="$(date -u +%Y%m%dT%H%M%SZ)"',
    '    final="$BACKUP_DIR/$stamp-${sha:0:7}.dump"',
    '    tmp="$(mktemp "$BACKUP_DIR/.backup.XXXXXX.tmp")"',
    '    trap \'rm -f -- "$tmp"\' EXIT',
    '    chmod 600 "$tmp"',
    '    if ! /usr/bin/timeout 600 /usr/sbin/runuser -u postgres -- /usr/bin/pg_dump -Fc --dbname="$DATABASE" > "$tmp"; then',
    '      echo "ERROR: pg_dump failed or exceeded the 10 minute timeout; database backup was not saved" >&2; exit 1',
    "    fi",
    '    mv -fT -- "$tmp" "$final"',
    "    trap - EXIT",
    '    find "$BACKUP_DIR" -maxdepth 1 -type f -name "*.dump" -print | sort -r | tail -n +6 | while IFS= read -r old; do rm -f -- "$old"; done',
    "    ;;",
    "  migrate|seed)",
    '    if [[ "$1" == migrate ]]; then cmd="$MIGRATE_CMD"; else cmd="$SEED_CMD"; fi',
    '    if [[ -z "$cmd" ]]; then echo "ERROR: no $1 command was set when bootstrap wrote this script; run bootstrap again" >&2; exit 1; fi',
    "    # Only migrate.env (owner role DATABASE_URL, APP_DATABASE_URL, seed values)",
    "    # and release.env; nothing writable but the private /tmp.",
    '    samohost_build_unit "$1" 900 "" "$MIGRATE_ENV" "" "$cmd"',
    "    ;;",
    "  release)",
    "    # Root does not read or walk build/: the copy runs as the build user in the",
    "    # copy unit. Ownership steps, and why each is safe:",
    "    # - root creates the destination fresh in releases/ (root:<app>-run 750; only",
    "    #   root creates entries there) and gives it to the build user for the copy;",
    "    #   <app>-run cannot enter it (mode 700). No other process has a descriptor",
    "    #   into it: the copy unit runs cp, not repository code, without network or",
    "    #   unix sockets, and its processes end with the unit; pkill follows.",
    "    # - root then takes the folder (root:root 700) before anything else, so no",
    "    #   other user can reach an entry in it by path.",
    "    # - only then root walks the result: removes special files, sets owner",
    "    #   root:<app>-run and modes without setuid, setgid and world bits. Every",
    "    #   entry is a new file made by cp (no hard links are kept), so chown and",
    "    #   chmod change no other file of the server. Symbolic links stay links;",
    "    #   the service follows them with its own rights.",
    '    if [[ "$(cat /proc/sys/fs/protected_hardlinks 2>/dev/null || echo 0)" != 1 ]]; then',
    '      echo "ERROR: fs.protected_hardlinks is not 1; refusing to make a release" >&2; exit 1',
    "    fi",
    '    pkill -KILL -u "$BUILD_USER" 2>/dev/null || true',
    "    # Before the copy: only current and previous stay, so at most three",
    "    # releases exist while the new one is copied.",
    "    samohost_prune",
    '    name="$(date -u +%Y%m%dT%H%M%SZ)-$$"',
    '    new="$RELEASES/$name"',
    '    dest="$new.tmp"',
    '    mkdir -m 700 -- "$dest"',
    '    chown "$BUILD_USER:$BUILD_USER" "$dest"',
    "    copy_rc=0",
    '    samohost_copy_unit "$dest" || copy_rc=$?',
    '    pkill -KILL -u "$BUILD_USER" 2>/dev/null || true',
    '    chown root:root "$dest"',
    '    chmod 700 "$dest"',
    '    if [[ "$copy_rc" -ne 0 ]]; then rm -rf -- "$dest"; echo "ERROR: the copy of build/ failed; no release was made" >&2; exit 1; fi',
    '    find "$dest" -mindepth 1 ! -type f ! -type d ! -type l -delete',
    '    rm -f -- "$dest/.npmrc"',
    '    chown -hR "root:$RUN_USER" "$dest"',
    '    chmod -R u=rwX,g=rX,o=,ug-s "$dest"',
    '    mv -T -- "$dest" "$new"',
    "    # previous is always the release that was current before this one.",
    '    if [[ -L "$CURRENT" ]]; then samohost_switch_link "$PREVIOUS" "$(readlink -- "$CURRENT")"; else rm -f -- "$PREVIOUS"; fi',
    '    samohost_switch_link "$CURRENT" "releases/$name"',
    "    # Keep the current and the previous release only. current is switched, so a",
    "    # failed removal is a warning, not a failed release.",
    "    samohost_prune",
    '    echo "release: $CURRENT -> releases/$name"',
    "    ;;",
    "  rollback)",
    "    # No previous release (a first release failed): remove current, so a restart",
    "    # or reboot leaves the unit failed instead of running the failed release, and",
    "    # the next release does not keep it as previous. Exit 3 tells the deploy.",
    '    if [[ ! -L "$PREVIOUS" ]]; then rm -f -- "$CURRENT"; echo "rollback: no previous release; removed $CURRENT" >&2; exit 3; fi',
    '    if [[ ! -d "$PREVIOUS/" ]]; then echo "ERROR: rollback: the previous release $(readlink -- "$PREVIOUS") does not exist" >&2; exit 1; fi',
    '    samohost_switch_link "$CURRENT" "$(readlink -- "$PREVIOUS")"',
    '    echo "rollback: $CURRENT -> $(readlink -- "$CURRENT")"',
    "    ;;",
    "  cleanup)",
    '    pkill -KILL -u "$BUILD_USER" 2>/dev/null || true',
    "    ;;",
    "  *)",
    `    echo "usage: $0 ${BUILD_STEP_NAMES.join("|")}" >&2; exit 2`,
    "    ;;",
    "esac",
    "",
  ].join("\n");
}
